import { describe, it, expect } from 'vitest';
import {
  GRID3X_GLYPHS,
  grid3ImageName,
  glyphForGrid3Image,
  isAutoGeneratedCellLabel,
  friendlyCellLabel,
  isDefaultWorkspaceLabel,
  deriveCellPresentation,
} from './grid3Images';

describe('grid3ImageName', () => {
  it('returns null for missing or non-string refs', () => {
    expect(grid3ImageName(undefined)).toBeNull();
    expect(grid3ImageName(null)).toBeNull();
    expect(grid3ImageName('')).toBeNull();
    expect(grid3ImageName(42 as unknown as string)).toBeNull();
  });

  it('parses [GRID3X] bracket refs', () => {
    expect(grid3ImageName('[GRID3X]delete_letter.wmf')).toBe('delete_letter');
    expect(grid3ImageName('[GRID3X]enter')).toBe('enter');
    expect(grid3ImageName('[grid3x]SHIFT.WMF')).toBe('shift');
  });

  it('takes the last path segment of bracketed library refs', () => {
    expect(grid3ImageName('[Widgit]computer/keyboard.png')).toBe('keyboard');
    expect(grid3ImageName('[SymbolStix]food/apple.png')).toBe('apple');
  });

  it('parses plain paths and filenames', () => {
    expect(grid3ImageName('delete_letter.wmf')).toBe('delete_letter');
    expect(grid3ImageName('Grids/Keyboard/backspace.png')).toBe('backspace');
  });

  it('handles a bare extension', () => {
    expect(grid3ImageName('.wmf')).toBeNull();
  });
});

describe('glyphForGrid3Image', () => {
  it('matches exact dictionary entries', () => {
    for (const [name, glyph] of Object.entries(GRID3X_GLYPHS)) {
      expect(glyphForGrid3Image(`[GRID3X]${name}.wmf`)).toBe(glyph);
    }
  });

  it('applies prefix-anchored fuzzy rules', () => {
    expect(glyphForGrid3Image('[GRID3X]delete_a_letter.wmf')).toBe('⌫');
    expect(glyphForGrid3Image('[GRID3X]shift_lock.wmf')).toBe('⇧');
    expect(glyphForGrid3Image('[GRID3X]speak_this.wmf')).toBe('🔊');
  });

  it('does not false-positive on lookalike words', () => {
    expect(glyphForGrid3Image('[GRID3X]table.wmf')).toBeNull();
    expect(glyphForGrid3Image('[GRID3X]tablet.wmf')).toBeNull();
    expect(glyphForGrid3Image('[GRID3X]spaceship.wmf')).toBeNull();
    expect(glyphForGrid3Image('[GRID3X]tabby_cat.wmf')).toBeNull();
  });

  it('returns null for unknown or missing refs', () => {
    expect(glyphForGrid3Image(undefined)).toBeNull();
    expect(glyphForGrid3Image('[GRID3X]something_new.wmf')).toBeNull();
    expect(glyphForGrid3Image('2-3-0-text-0.png')).toBeNull();
  });
});

describe('isAutoGeneratedCellLabel', () => {
  it('detects Cell_N and AutoContent_N synthetic labels', () => {
    expect(isAutoGeneratedCellLabel('Cell_43')).toBe(true);
    expect(isAutoGeneratedCellLabel('Cell_0')).toBe(true);
    expect(isAutoGeneratedCellLabel('AutoContent_7')).toBe(true);
  });

  it('rejects real labels', () => {
    expect(isAutoGeneratedCellLabel('backspace')).toBe(false);
    expect(isAutoGeneratedCellLabel('Cell_43_extra')).toBe(false);
    expect(isAutoGeneratedCellLabel('Cell')).toBe(false);
    expect(isAutoGeneratedCellLabel('')).toBe(false);
    expect(isAutoGeneratedCellLabel(undefined)).toBe(false);
  });
});

describe('friendlyCellLabel', () => {
  it('derives a label from the image reference', () => {
    expect(friendlyCellLabel('Cell_43', '[GRID3X]delete_letter.wmf')).toBe('delete letter');
    expect(friendlyCellLabel('AutoContent_7', 'Grids/Keyboard/clear.png')).toBe('clear');
  });

  it('returns null for coordinate-named dynamic images (no number soup)', () => {
    expect(friendlyCellLabel('Cell_5', 'Grids/Keyboard/2-3-0-text-0.png')).toBeNull();
    expect(friendlyCellLabel('Cell_5', '2-3-0-text-0.png')).toBeNull();
  });

  it('returns null for non-synthetic labels or missing refs', () => {
    expect(friendlyCellLabel('backspace', '[GRID3X]delete_letter.wmf')).toBeNull();
    expect(friendlyCellLabel('Cell_43', undefined)).toBeNull();
    expect(friendlyCellLabel('Cell_43', '.wmf')).toBeNull();
  });
});

describe('isDefaultWorkspaceLabel', () => {
  it('matches the loader defaults: bare and subtyped', () => {
    expect(isDefaultWorkspaceLabel('Workspace')).toBe(true);
    expect(isDefaultWorkspaceLabel('workspace')).toBe(true);
    expect(isDefaultWorkspaceLabel('Chat Workspace')).toBe(true);
    expect(isDefaultWorkspaceLabel('Keyboard Workspace')).toBe(true);
  });

  it('keeps real workspace labels', () => {
    expect(isDefaultWorkspaceLabel('My sentence bar')).toBe(false);
    expect(isDefaultWorkspaceLabel('Workspace notes')).toBe(false);
    expect(isDefaultWorkspaceLabel(undefined)).toBe(false);
  });
});

describe('deriveCellPresentation', () => {
  it('derives glyph + friendly label for image-only GRID3X cells', () => {
    const p = deriveCellPresentation(
      { label: 'Cell_43', message: null },
      '[GRID3X]delete_letter.wmf',
      false
    );
    expect(p.glyph).toBe('⌫');
    expect(p.displayLabel).toBe('delete letter');
    expect(p.hideLabel).toBe(false); // friendly label is shown
    expect(p.alt).toBe('delete letter');
  });

  it('hides synthetic labels when only a glyph or image is available', () => {
    const p = deriveCellPresentation({ label: 'Cell_5', message: null }, undefined, true);
    expect(p.glyph).toBeNull();
    expect(p.hideLabel).toBe(true);
    expect(p.displayLabel).toBe('Cell_5');
    expect(p.alt).toBe(''); // not announced to screen readers
  });

  it('keeps real labels untouched', () => {
    const p = deriveCellPresentation({ label: 'hello', message: 'hello' }, undefined, false);
    expect(p.displayLabel).toBe('hello');
    expect(p.hideLabel).toBe(false);
    expect(p.alt).toBe('hello');
  });

  it('always provides the glyph so failed loads can fall back', () => {
    const p = deriveCellPresentation(
      { label: 'Cell_9', message: null },
      '[GRID3X]enter.wmf',
      true
    );
    expect(p.glyph).toBe('↵');
    expect(p.displayLabel).toBe('enter');
  });
});
